// ============================================================
// 地形生成 (DEM 5m メッシュ)
// ============================================================
function generateTerrain() {
  const elevations = [];
  for (let j = 0; j < GRID; j++) {
    for (let i = 0; i < GRID; i++) {
      const x = (i - GRID / 2) * CELL;
      const z = (j - GRID / 2) * CELL;
      let elev = ELEV_BASE;
      elev += 0.003 * z;
      const dYamanote = Math.abs(z - 10);
      elev -= 1.2 * Math.exp(-Math.pow(dYamanote / 18, 2));
      const dMeiji = Math.abs(z + 70);
      elev -= 0.5 * Math.exp(-Math.pow(dMeiji / 12, 2));
      const dMarunouchi = Math.abs(z + 130);
      elev -= 0.6 * Math.exp(-Math.pow(dMarunouchi / 14, 2));
      const dOtsukaDori = Math.abs(x + 80);
      elev -= 0.3 * Math.exp(-Math.pow(dOtsukaDori / 10, 2));
      elev += (rand() - 0.5) * 0.6;
      elevations.push(Math.round((elev - ELEV_BASE) * 100) / 100);
    }
  }
  return elevations;
}

